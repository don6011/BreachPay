/// <reference lib="deno.ns" />

import { createClient } from "https://esm.sh/@supabase/supabase-js@2";
import { jsPDF } from "https://esm.sh/jspdf@2.5.2";

const corsHeaders = {
  "Access-Control-Allow-Origin": "*",
  "Access-Control-Allow-Headers":
    "authorization, x-client-info, apikey, content-type, x-supabase-client-platform, x-supabase-client-platform-version, x-supabase-client-runtime, x-supabase-client-runtime-version",
};

function fmt(d: string | null): string {
  if (!d) return "—";
  return new Date(d).toLocaleDateString("en-US", { year: "numeric", month: "long", day: "numeric" });
}

function money(n: number | null): string {
  if (n == null) return "—";
  return `$${Number(n).toLocaleString("en-US", { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`;
}

function safe(s: string | null | undefined): string {
  return s || "—";
}

function buildPdf(claim: any, settlement: any, application: any, documents: any[], match: any): Uint8Array {
  const doc = new jsPDF({ unit: "mm", format: "a4" });
  const pw = doc.internal.pageSize.getWidth();
  const ph = doc.internal.pageSize.getHeight();
  const margin = 18;
  const contentW = pw - margin * 2;
  let y = margin;

  // Brand colors (RGB)
  const navy = [7, 10, 18];
  const panelNavy = [14, 23, 38];
  const emerald = [0, 230, 168];
  const teal = [0, 191, 166];
  const gold = [200, 162, 76];
  const dark = [15, 23, 42];
  const gray = [100, 116, 139];
  const lightGray = [148, 163, 184];
  const white = [255, 255, 255];
  const cardBg = [16, 24, 40];
  const cardBorder = [30, 41, 59];

  function addFooter() {
    const totalPages = doc.getNumberOfPages();
    for (let i = 1; i <= totalPages; i++) {
      doc.setPage(i);
      // Footer line
      doc.setDrawColor(...emerald as [number, number, number]);
      doc.setLineWidth(0.3);
      doc.line(margin, ph - 18, pw - margin, ph - 18);
      // Footer text
      doc.setFontSize(7);
      doc.setTextColor(...lightGray as [number, number, number]);
      doc.setFont("helvetica", "normal");
      doc.text("Generated by BreachPay  •  Settlement Recovery Platform  •  breachpay.app", margin, ph - 14);
      doc.text("BreachPay is not a law firm and does not provide legal advice.", margin, ph - 10.5);
      doc.setFont("helvetica", "bold");
      doc.text(`Page ${i} of ${totalPages}`, pw - margin - 22, ph - 14);
    }
  }

  function checkPage(needed: number) {
    if (y + needed > ph - 25) { doc.addPage(); y = margin; }
  }

  function sectionHeading(text: string) {
    checkPage(16);
    y += 8;
    doc.setFontSize(12);
    doc.setFont("helvetica", "bold");
    doc.setTextColor(...emerald as [number, number, number]);
    doc.text(text.toUpperCase(), margin, y);
    y += 2;
    doc.setDrawColor(...emerald as [number, number, number]);
    doc.setLineWidth(0.6);
    doc.line(margin, y, margin + 45, y);
    doc.setLineWidth(0.15);
    doc.setDrawColor(...cardBorder as [number, number, number]);
    doc.line(margin + 45, y, pw - margin, y);
    y += 6;
  }

  function tableRow(label: string, value: string, highlight = false) {
    checkPage(7);
    // Alternating subtle background
    doc.setFontSize(9);
    doc.setFont("helvetica", "bold");
    doc.setTextColor(...dark as [number, number, number]);
    doc.text(label, margin + 2, y + 3.5);
    doc.setFont("helvetica", "normal");
    if (highlight) {
      doc.setTextColor(...emerald as [number, number, number]);
      doc.setFont("helvetica", "bold");
    } else {
      doc.setTextColor(60, 60, 60);
    }
    const lines = doc.splitTextToSize(value, contentW - 55);
    doc.text(lines, margin + 52, y + 3.5);
    y += Math.max(6.5, lines.length * 5) + 0.5;
    // Subtle divider
    doc.setDrawColor(220, 225, 235);
    doc.setLineWidth(0.1);
    doc.line(margin, y - 0.5, pw - margin, y - 0.5);
  }

  function cardBox(x: number, boxY: number, w: number, h: number) {
    doc.setFillColor(248, 250, 252);
    doc.setDrawColor(200, 210, 225);
    doc.setLineWidth(0.3);
    doc.roundedRect(x, boxY, w, h, 2, 2, "FD");
  }

  // =============================================
  // COVER / HEADER
  // =============================================

  // Top accent bar
  doc.setFillColor(...emerald as [number, number, number]);
  doc.rect(0, 0, pw, 3, "F");

  // Brand name
  y = 20;
  doc.setFontSize(28);
  doc.setFont("helvetica", "bold");
  doc.setTextColor(...dark as [number, number, number]);
  doc.text("BREACHPAY", margin, y);
  y += 7;
  doc.setFontSize(11);
  doc.setFont("helvetica", "normal");
  doc.setTextColor(...gray as [number, number, number]);
  doc.text("Compensation Recovery Packet", margin, y);
  y += 5;

  // Claim ID & timestamp line
  doc.setFontSize(8);
  doc.setTextColor(...lightGray as [number, number, number]);
  const timestamp = new Date().toISOString().slice(0, 16).replace("T", " ");
  doc.text(`Claim ID: ${(claim.id || "").slice(0, 8).toUpperCase()}  •  Generated: ${timestamp} UTC`, margin, y);
  y += 3;

  // Accent divider
  doc.setDrawColor(...emerald as [number, number, number]);
  doc.setLineWidth(0.8);
  doc.line(margin, y, pw - margin, y);
  y += 5;

  // =============================================
  // VERIFIED SETTLEMENT BADGE
  // =============================================
  checkPage(22);
  const badgeW = contentW;
  const badgeH = 18;
  const badgeY = y;

  // Badge background
  doc.setFillColor(240, 253, 244);
  doc.setDrawColor(...emerald as [number, number, number]);
  doc.setLineWidth(0.4);
  doc.roundedRect(margin, badgeY, badgeW, badgeH, 2.5, 2.5, "FD");

  // Shield icon (text placeholder)
  doc.setFontSize(14);
  doc.setTextColor(...emerald as [number, number, number]);
  doc.text("✓", margin + 5, badgeY + 8);

  // Badge text
  doc.setFontSize(11);
  doc.setFont("helvetica", "bold");
  doc.setTextColor(22, 101, 52);
  doc.text("VERIFIED SETTLEMENT", margin + 14, badgeY + 7);

  const confScore = match?.confidence_score ?? "—";
  doc.setFontSize(9);
  doc.setFont("helvetica", "normal");
  doc.setTextColor(34, 120, 70);
  doc.text(`Confidence Score: ${confScore}%  •  This claim has been organized, validated, and is ready for review.`, margin + 14, badgeY + 13);

  y = badgeY + badgeH + 6;

  // =============================================
  // SETTLEMENT SUMMARY CARD
  // =============================================
  sectionHeading("Settlement Summary");

  const cardStartY = y;
  const cardH = 38;
  cardBox(margin, cardStartY, contentW, cardH);

  // Card content - 3 columns
  const col1X = margin + 5;
  const col2X = margin + contentW * 0.4;
  const col3X = margin + contentW * 0.72;
  let cardY = cardStartY + 6;

  doc.setFontSize(7);
  doc.setFont("helvetica", "normal");
  doc.setTextColor(...lightGray as [number, number, number]);
  doc.text("SETTLEMENT", col1X, cardY);
  doc.text("ESTIMATED PAYOUT", col2X, cardY);
  doc.text("DEADLINE", col3X, cardY);

  cardY += 5;
  doc.setFontSize(10);
  doc.setFont("helvetica", "bold");
  doc.setTextColor(...dark as [number, number, number]);
  const settlementName = safe(settlement?.name);
  const nameLines = doc.splitTextToSize(settlementName, contentW * 0.35);
  doc.text(nameLines, col1X, cardY);

  doc.setTextColor(...emerald as [number, number, number]);
  doc.text(`${money(settlement?.payout_min)} – ${money(settlement?.payout_max)}`, col2X, cardY);

  doc.setTextColor(...dark as [number, number, number]);
  doc.text(fmt(settlement?.claim_deadline || settlement?.deadline), col3X, cardY);

  cardY += 8;
  doc.setFontSize(8);
  doc.setFont("helvetica", "normal");
  doc.setTextColor(...gray as [number, number, number]);
  doc.text(`Company: ${safe(settlement?.company)}`, col1X, cardY);
  doc.text(`Breach Year: ${settlement?.breach_year || "—"}`, col2X, cardY);

  if (settlement?.administrator_name) {
    cardY += 4.5;
    doc.text(`Administrator: ${settlement.administrator_name}`, col1X, cardY);
  }
  if (settlement?.case_number) {
    doc.text(`Case: ${settlement.case_number}`, col2X, cardY);
  }

  y = cardStartY + cardH + 6;

  // =============================================
  // CLAIM STATUS
  // =============================================
  sectionHeading("Claim Status");

  tableRow("Claim Status", (claim.status || "draft").toUpperCase(), true);
  tableRow("Filed Date", fmt(claim.filed_at));
  tableRow("Estimated Payout", money(claim.est_payout), true);
  tableRow("Platform Fee", `${claim.fee_percent || 15}%`);
  if (claim.submission_channel) tableRow("Submission Channel", claim.submission_channel);
  if (claim.external_submission_ref) tableRow("External Ref", claim.external_submission_ref);

  // =============================================
  // MATCH CONFIDENCE
  // =============================================
  if (match) {
    sectionHeading("Match Confidence");

    // Confidence highlight box
    checkPage(18);
    const confBoxY = y;
    const confBoxH = 14;
    cardBox(margin, confBoxY, contentW, confBoxH);

    doc.setFontSize(16);
    doc.setFont("helvetica", "bold");
    doc.setTextColor(...emerald as [number, number, number]);
    doc.text(`${match.confidence_score || "—"}%`, margin + 6, confBoxY + 8);

    doc.setFontSize(10);
    doc.setTextColor(...dark as [number, number, number]);
    const levelText = (match.confidence_level || "").charAt(0).toUpperCase() + (match.confidence_level || "").slice(1);
    doc.text(`– ${levelText}`, margin + 22, confBoxY + 8);

    y = confBoxY + confBoxH + 4;

    // Match reasons as bullet list
    if (match.match_reason) {
      const reasons = match.match_reason.split(/[,;\n]+/).map((r: string) => r.trim()).filter(Boolean);
      doc.setFontSize(8.5);
      doc.setFont("helvetica", "normal");
      doc.setTextColor(...dark as [number, number, number]);
      for (const reason of reasons) {
        checkPage(6);
        doc.setTextColor(...emerald as [number, number, number]);
        doc.text("•", margin + 4, y);
        doc.setTextColor(...dark as [number, number, number]);
        doc.text(reason, margin + 9, y);
        y += 5;
      }
    }
  }

  // =============================================
  // CLAIMANT INFORMATION
  // =============================================
  sectionHeading("Claimant Information");

  tableRow("Full Name", safe(application?.full_name));
  tableRow("Email", safe(application?.email));
  tableRow("Phone", safe(application?.phone));
  tableRow("Address", safe(application?.address));
  if (application?.breach_experience) {
    tableRow("Breach Experience", application.breach_experience);
  }

  // Eligibility Answers
  const eligibility = application?.eligibility_answers || {};
  const entries = Object.entries(eligibility);
  if (entries.length > 0) {
    sectionHeading("Eligibility Answers");
    for (const [k, v] of entries) {
      tableRow(k.replace(/_/g, " ").replace(/\b\w/g, (c: string) => c.toUpperCase()), String(v));
    }
  }

  // =============================================
  // EVIDENCE SECTION (new page)
  // =============================================
  doc.addPage();

  // Top accent bar on new pages
  doc.setFillColor(...emerald as [number, number, number]);
  doc.rect(0, 0, pw, 1.5, "F");

  y = margin;
  sectionHeading(`Evidence Index (${documents.length} document${documents.length !== 1 ? "s" : ""})`);

  if (documents.length > 0) {
    // Table header
    checkPage(10);
    doc.setFillColor(241, 245, 249);
    doc.setDrawColor(200, 210, 225);
    doc.setLineWidth(0.2);
    doc.roundedRect(margin, y, contentW, 7, 1, 1, "FD");
    doc.setFontSize(7);
    doc.setFont("helvetica", "bold");
    doc.setTextColor(...dark as [number, number, number]);
    const cols = [margin + 3, margin + 56, margin + 88, margin + 112, margin + 138];
    doc.text("FILE NAME", cols[0], y + 4.5);
    doc.text("CATEGORY", cols[1], y + 4.5);
    doc.text("STATUS", cols[2], y + 4.5);
    doc.text("SIZE", cols[3], y + 4.5);
    doc.text("UPLOADED", cols[4], y + 4.5);
    y += 9;

    doc.setFont("helvetica", "normal");
    doc.setFontSize(7.5);
    for (let i = 0; i < documents.length; i++) {
      const d = documents[i];
      checkPage(7);
      // Alternating row bg
      if (i % 2 === 0) {
        doc.setFillColor(249, 250, 251);
        doc.rect(margin, y - 1, contentW, 6.5, "F");
      }
      doc.setTextColor(50, 55, 65);
      doc.text((d.file_name || "").slice(0, 28), cols[0], y + 3);
      doc.text(safe(d.doc_type).slice(0, 14), cols[1], y + 3);
      // Status with color
      const status = safe(d.status);
      if (status.toLowerCase() === "verified") {
        doc.setTextColor(...emerald as [number, number, number]);
      } else {
        doc.setTextColor(...gray as [number, number, number]);
      }
      doc.setFont("helvetica", "bold");
      doc.text(status, cols[2], y + 3);
      doc.setFont("helvetica", "normal");
      doc.setTextColor(50, 55, 65);
      doc.text(d.file_size ? `${(d.file_size / 1024).toFixed(1)} KB` : "—", cols[3], y + 3);
      doc.text(fmt(d.created_at).slice(0, 18), cols[4], y + 3);
      y += 6.5;
    }
  } else {
    checkPage(14);
    cardBox(margin, y, contentW, 12);
    doc.setFontSize(9);
    doc.setTextColor(...gray as [number, number, number]);
    doc.setFont("helvetica", "italic");
    doc.text("No supporting documents were attached to this claim.", margin + 5, y + 7.5);
    y += 16;
  }

  // =============================================
  // DECLARATION PAGE
  // =============================================
  doc.addPage();

  // Top accent bar
  doc.setFillColor(...emerald as [number, number, number]);
  doc.rect(0, 0, pw, 1.5, "F");

  y = margin;
  sectionHeading("Claimant Declaration");

  doc.setFontSize(10);
  doc.setTextColor(...dark as [number, number, number]);
  doc.setFont("helvetica", "normal");

  const claimantName = application?.full_name || "________________________";

  const decl1 = doc.splitTextToSize(
    `I, ${claimantName}, hereby declare that the information provided in this claim packet is true and accurate to the best of my knowledge. I understand that submitting false or misleading information may result in the denial of my claim and potential legal consequences.`,
    contentW
  );
  doc.text(decl1, margin, y);
  y += decl1.length * 5 + 5;

  const decl2 = doc.splitTextToSize(
    `I confirm that I was affected by the ${safe(settlement?.company)} data breach${settlement?.breach_year ? ` (${settlement.breach_year})` : ""} and that I am eligible to participate in the ${safe(settlement?.name)} settlement as described herein.`,
    contentW
  );
  doc.text(decl2, margin, y);
  y += decl2.length * 5 + 5;

  const decl3 = doc.splitTextToSize(
    `I authorize BreachPay to act on my behalf in processing this claim and understand that a platform fee of ${claim.fee_percent || 15}% will apply to any awarded compensation.`,
    contentW
  );
  doc.text(decl3, margin, y);
  y += decl3.length * 5 + 14;

  // Signature area
  checkPage(35);

  doc.setDrawColor(...dark as [number, number, number]);
  doc.setLineWidth(0.3);
  doc.line(margin, y, margin + 72, y);
  doc.line(pw - margin - 55, y, pw - margin, y);

  y += 5;
  doc.setFontSize(8);
  doc.setTextColor(...gray as [number, number, number]);
  doc.setFont("helvetica", "normal");
  doc.text("Signature", margin, y);
  doc.text("Date", pw - margin - 55, y);
  y += 12;

  // Certification status
  doc.setFontSize(8);
  if (application?.certifications_signed) {
    doc.setTextColor(22, 101, 52);
    doc.text("✓  Digital certifications were signed at submission.", margin, y);
  } else {
    doc.setTextColor(180, 80, 20);
    doc.text("⚠  Digital certifications were not signed.", margin, y);
  }
  y += 5;
  if (application?.disclaimer_accepted_at) {
    doc.setTextColor(...gray as [number, number, number]);
    doc.text(`Disclaimer accepted on ${fmt(application.disclaimer_accepted_at)}.`, margin, y);
  }

  // =============================================
  // FOOTER ON EVERY PAGE
  // =============================================
  addFooter();

  return new Uint8Array(doc.output("arraybuffer"));
}

Deno.serve(async (req) => {
  if (req.method === "OPTIONS") {
    return new Response(null, { headers: corsHeaders });
  }

  if (req.method !== "POST") {
    return new Response(JSON.stringify({ ok: false, error: "method_not_allowed" }), {
      status: 405,
      headers: { ...corsHeaders, "Content-Type": "application/json" },
    });
  }

  try {
    const supabaseUrl = Deno.env.get("SUPABASE_URL")!;
    const serviceKey = Deno.env.get("SUPABASE_SERVICE_ROLE_KEY")!;
    const bucket = Deno.env.get("PACKET_BUCKET") ?? "claim-packets";

    const authHeader = req.headers.get("Authorization");
    if (!authHeader?.startsWith("Bearer ")) {
      return new Response(JSON.stringify({ ok: false, error: "unauthorized" }), {
        status: 401,
        headers: { ...corsHeaders, "Content-Type": "application/json" },
      });
    }

    const supabaseUser = createClient(supabaseUrl, Deno.env.get("SUPABASE_ANON_KEY") ?? "", {
      global: { headers: { Authorization: authHeader } },
    });

    const token = authHeader.replace("Bearer ", "");
    const { data: claimsData, error: authErr } = await supabaseUser.auth.getClaims(token);
    if (authErr || !claimsData?.claims) {
      return new Response(JSON.stringify({ ok: false, error: "unauthorized" }), {
        status: 401,
        headers: { ...corsHeaders, "Content-Type": "application/json" },
      });
    }
    const userId = claimsData.claims.sub as string;

    const { claim_id } = await req.json();
    if (!claim_id) {
      return new Response(JSON.stringify({ ok: false, error: "missing_claim_id" }), {
        status: 400,
        headers: { ...corsHeaders, "Content-Type": "application/json" },
      });
    }

    const admin = createClient(supabaseUrl, serviceKey);

    const { data: claim, error: claimErr } = await admin
      .from("claims")
      .select("*")
      .eq("id", claim_id)
      .maybeSingle();

    if (claimErr || !claim) {
      return new Response(JSON.stringify({ ok: false, error: "claim_not_found" }), {
        status: 404,
        headers: { ...corsHeaders, "Content-Type": "application/json" },
      });
    }

    const { data: isAdminData } = await admin.rpc("is_admin", { p_user: userId });
    if (claim.user_id !== userId && !isAdminData) {
      return new Response(JSON.stringify({ ok: false, error: "forbidden" }), {
        status: 403,
        headers: { ...corsHeaders, "Content-Type": "application/json" },
      });
    }

    const [settlementRes, appRes, docsRes, matchRes] = await Promise.all([
      admin.from("settlements").select("*").eq("id", claim.settlement_id).maybeSingle(),
      admin.from("claim_applications").select("*").eq("claim_id", claim_id).maybeSingle(),
      admin.from("claim_documents").select("*").eq("claim_id", claim_id).order("created_at", { ascending: true }),
      claim.match_id
        ? admin.from("settlement_matches").select("confidence_score, confidence_level, match_reason").eq("id", claim.match_id).maybeSingle()
        : Promise.resolve({ data: null }),
    ]);

    // Generate real PDF
    const pdfBytes = buildPdf(claim, settlementRes.data, appRes.data, docsRes.data || [], matchRes.data);

    const friendlyName = `BreachPay-Claim-Packet-${claim_id.slice(0, 8)}.pdf`;

    // Insert claim_packets row
    const { data: packet, error: packetInsertErr } = await admin
      .from("claim_packets")
      .insert({
        claim_id,
        generated_by: userId,
        status: "generated",
        pdf_file_name: friendlyName,
        meta: {
          settlement_name: settlementRes.data?.name,
          company: settlementRes.data?.company,
          document_count: docsRes.data?.length || 0,
          has_application: !!appRes.data,
          has_match: !!matchRes.data,
        },
      })
      .select("id")
      .single();

    if (packetInsertErr || !packet) {
      throw new Error(`packet_insert_failed: ${packetInsertErr?.message ?? "unknown"}`);
    }

    const packetId = packet.id as string;
    const storagePath = `${claim_id}/${packetId}.pdf`;

    // Upload real PDF binary
    const { error: uploadErr } = await admin.storage
      .from(bucket)
      .upload(storagePath, pdfBytes, {
        contentType: "application/pdf",
        upsert: true,
      });

    if (uploadErr) {
      await admin.from("claim_packets").update({
        status: "failed",
        last_error: uploadErr.message,
      }).eq("id", packetId);
      throw new Error(`upload_failed: ${uploadErr.message}`);
    }

    // Update packet with storage path
    await admin.from("claim_packets").update({
      pdf_storage_path: storagePath,
    }).eq("id", packetId);

    // Update claims.packet_generated_at
    await admin.from("claims").update({
      packet_generated_at: new Date().toISOString(),
    }).eq("id", claim_id);

    return new Response(JSON.stringify({
      ok: true,
      packet_id: packetId,
      storage_path: storagePath,
      file_name: friendlyName,
    }), {
      headers: { ...corsHeaders, "Content-Type": "application/json" },
    });
  } catch (e) {
    const msg = e instanceof Error ? e.message : String(e);
    return new Response(JSON.stringify({ ok: false, error: msg }), {
      status: 500,
      headers: { ...corsHeaders, "Content-Type": "application/json" },
    });
  }
});
